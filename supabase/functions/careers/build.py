"""Builds index.ts (the single file to paste into Supabase → Edge Functions) from handler.ts + embed.js."""
import json
from pathlib import Path

here = Path(__file__).parent
src = (here / "handler.ts").read_text()
embed = (here / "embed.js").read_text()
marker = 'import { createClient } from "npm:@supabase/supabase-js@2";\n'
assert marker in src
out = ("// GENERATED by build.py from handler.ts and embed.js. Edit those, then run: python build.py\n"
       + src.replace(marker, marker + "\n// The widget, served at /careers/embed.js\nconst EMBED_JS = " + json.dumps(embed) + ";\n", 1))
(here / "index.ts").write_text(out)
print("wrote", here / "index.ts", len(out), "bytes")
